/**
 * Regenerates src/blocklist-data.ts from the bundled scam lists, at pinned commits.
 * Usage: pnpm --filter @plaintx/registry build:blocklist
 * To update a list, change its commit below, run this, review the diff and update ADR 0008.
 */
import { writeFile } from "node:fs/promises";

const SOURCES = {
  "mew-darklist": {
    repo: "MyEtherWallet/ethereum-lists",
    commit: "8f86cba9b58db79608ece8fa784775b3c41e2e26",
    path: "src/addresses/addresses-darklist.json",
  },
  "forta-labelled-datasets": {
    repo: "forta-network/labelled-datasets",
    commit: "40a9c2f2bd7e9ddfdd0f3540db589f0288e1e88a",
    path: "labels/1/malicious_smart_contracts.csv",
  },
};

const ADDRESS = /^0x[0-9a-fA-F]{40}$/;

async function download({ repo, commit, path }) {
  const res = await fetch(`https://raw.githubusercontent.com/${repo}/${commit}/${path}`);
  if (!res.ok) throw new Error(`${repo}/${path}: HTTP ${res.status}`);
  return res.text();
}

const clean = (text) => text.replace(/\s+/g, " ").trim().slice(0, 160);

/** address (lower case) -> [source, note]. The first source to list an address wins. */
const entries = new Map();
const add = (address, source, note) => {
  if (!ADDRESS.test(address)) throw new Error(`${source}: malformed address ${address}`);
  if (!entries.has(address.toLowerCase())) entries.set(address.toLowerCase(), [source, note]);
};

for (const e of JSON.parse(await download(SOURCES["mew-darklist"]))) {
  add(e.address.trim(), "mew-darklist", clean(e.comment ?? ""));
}

// Only rows with a public, non-Etherscan source: the rest are Etherscan labels (via Luabase),
// whose terms we have not cleared. Simple split is safe: these rows contain no quoted commas.
const [header, ...rows] = (await download(SOURCES["forta-labelled-datasets"])).trim().split("\n");
const col = Object.fromEntries(header.split(",").map((name, i) => [name, i]));
for (const row of rows) {
  const cells = row.split(",");
  const source = cells[col.source] ?? "";
  if (!source.startsWith("https://github.com/")) continue;
  const tag = cells[col.contract_tag] || "Exploit contract";
  add(
    cells[col.contract_address].trim(),
    "forta-labelled-datasets",
    clean(`${tag} (via ${source.replace("https://github.com/", "")})`),
  );
}

const lines = [...entries]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([address, [source, note]]) =>
      `  [${JSON.stringify(address)}, ${JSON.stringify(source)}, ${JSON.stringify(note)}],`,
  );

await writeFile(
  new URL("../src/blocklist-data.ts", import.meta.url),
  `// Generated by scripts/build-blocklist.mjs. Do not edit by hand.
import type { BlocklistEntry } from "./blocklist.js";

export const BLOCKLIST_ENTRIES: readonly BlocklistEntry[] = [
${lines.join("\n")}
];
`,
);
console.log(`Wrote ${entries.size} addresses`);
